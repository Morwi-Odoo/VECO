"""Fix the Studio-customized invoice QWeb reports for Odoo 19.

These reports (Factura Exportacion, Factura Dolares DVI[/copia], Factura
Dolares VECO[/con Comercio Exterior], Factura Nacional DVI[/Rev2], Factura
Nacional Veco copy(8)/Rev. Sep25) are `ir.ui.view` records generated by
Odoo Studio (module ``studio_customization``), not files tracked in this
repo. They still contained several patterns from Odoo <=16 that were
removed/renamed by Odoo 19:

- a stray ``style="color:#000000"`` attribute placed directly on a
  ``<t t-call="web.external_layout">`` node: any non ``t-`` attribute on a
  ``t-call`` is compiled as a python expression, and "color:#000000" isn't
  a valid expression.
- ``account.move.tax_totals_json`` (removed, replaced by the ``tax_totals``
  dict field, which also needs a ``currency`` value passed to
  ``account.document_tax_totals``).
- ``account.move._l10n_mx_edi_decode_cfdi()`` (removed, replaced by
  ``l10n_mx_edi.document._decode_cfdi_attachment()``).
- ``account.move._get_l10n_mx_edi_signed_edi_document()`` (removed).
- ``account.move._get_reconciled_info_JSON_values()`` (removed, replaced by
  the ``invoice_payments_widget`` field).
- ``account.move.l10n_mx_edi_origin`` (renamed to
  ``l10n_mx_edi_cfdi_origin``).
- ``account.move.l10n_mx_edi_cfdi_request`` (removed field, was used to
  decide whether to show the "signature required" banner).
- four of the reports never printed anything because they gated the
  document on ``o._get_name_invoice_report() == 'account.report_invoice_document'``,
  which is never true for an invoice whose CFDI was already stamped
  (l10n_mx_edi overrides that method to return
  ``'l10n_mx_edi.report_invoice_document'`` instead).
- ``account.move.line.display_type`` used to be ``False``/empty for a
  regular product line; Odoo 19 now sets it to ``'product'``. All ten
  documents guarded their line row with ``t-if="not line.display_type"``,
  which is now always false, so every invoice printed with an empty product
  table (subtotal/tax/total still computed fine since those come from
  ``tax_totals``, not from the line loop).
- the ``Odoo Studio: report_invoice_document copy(1) customization``
  overlay (inherited view on top of ``account.report_invoice_document_copy_1``,
  used by "Factura Nacional Veco copy(8)") references
  ``line.internal_note``, a field that doesn't exist (removed, or a custom
  field that was later deleted): the whole "Nota interna" column addition is
  dropped. The same overlay also overwrote a header ``<span>``'s ``t-field``
  attribute to ``line.name`` outside of the line loop, which would raise a
  ``NameError`` (``line`` undefined there); reverted to the value the Studio
  edit before it left in place (``o.line_ids``).

The "Comercio Exterior" (customs) block in these reports reads
``cfdi_vals['ext_trade_*']`` keys that no current python code populates;
those accesses are made safe with ``.get()`` here but will keep rendering
blank until that data extraction is reimplemented.
"""

import re

from odoo import api, SUPERUSER_ID

# (old, new) literal replacements safe to try on every affected document
# template: each is a no-op if the pattern isn't present.
LITERAL_FIXES = [
    (
        '<t t-call="web.external_layout" style="color:#000000">',
        '<t t-call="web.external_layout">',
    ),
    (
        "o._l10n_mx_edi_decode_cfdi()",
        "o.env['l10n_mx_edi.document']._decode_cfdi_attachment("
        "o.l10n_mx_edi_cfdi_attachment_id.raw)",
    ),
    (
        "bool(o._get_l10n_mx_edi_signed_edi_document())",
        "o.l10n_mx_edi_cfdi_state == 'sent'",
    ),
    (
        "o.l10n_mx_edi_cfdi_request in ('on_invoice', 'on_refund') "
        "and not is_cfdi_signed and o.edi_state != 'cancelled'",
        "o.move_type in ('out_invoice', 'out_refund') "
        "and not is_cfdi_signed and o.state != 'cancel'",
    ),
    (
        "o.sudo()._get_reconciled_info_JSON_values()",
        "o.sudo().invoice_payments_widget and "
        "o.sudo().invoice_payments_widget['content'] or []",
    ),
    (
        "o.l10n_mx_edi_origin",
        "o.l10n_mx_edi_cfdi_origin",
    ),
    (
        't-if="not line.display_type"',
        "t-if=\"line.display_type == 'product' or not line.display_type\"",
    ),
]

