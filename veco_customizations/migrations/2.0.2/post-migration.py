TAX_TOTALS_TEMPLATES_TO_REWRITE = [
    "account.document_tax_totals_copy_1",
    "account.document_tax_totals_copy_2",
    "account.document_tax_totals_copy_4",
    "account.document_tax_totals_copy_5",
    "account.document_tax_totals_copy_6",
    "account.document_tax_totals_copy_9",
]


def _get_view(env, key):
    return env["ir.ui.view"].search([("key", "=", key)], limit=1)


def migrate(cr, version):
    env = api.Environment(cr, SUPERUSER_ID, {})

    for key, tmpl in TAX_TOTALS_CALL_TARGETS.items():
        view = _get_view(env, key)
        if not view:
            continue
        arch = view.arch

        old_call = (
            '<t t-set="tax_totals" t-value="json.loads(o.tax_totals_json)"/>\n'
        )
        # indentation before the paired <t t-call="TMPL"/> varies between
        # views, so match it loosely instead of hard-coding whitespace.
        marker = f'<t t-call="{tmpl}"/>'
        idx = arch.find(old_call)
        if idx != -1:
            rest = arch[idx + len(old_call):]
            call_idx = rest.find(marker)
            if call_idx != -1 and rest[:call_idx].strip() == "":
                indent = rest[:call_idx]
                old_block = old_call + indent + marker
                new_block = (
                    f'<t t-if="o.tax_totals" t-call="{tmpl}">\n'
                    f"{indent}    <t t-set=\"tax_totals\" t-value=\"o.tax_totals\"/>\n"
                    f"{indent}    <t t-set=\"currency\" t-value=\"o.currency_id\"/>\n"
                    f"{indent}</t>"
                )
                arch = arch.replace(old_block, new_block)

        for old, new in LITERAL_FIXES:
            if old in arch:
                arch = arch.replace(old, new)

        # guard direct cfdi_vals['ext_trade_*'] access (Comercio Exterior
        # block): no current code populates these keys, so this only avoids
        # a KeyError crash, it does not restore the missing data.
        arch = re.sub(
            r"cfdi_vals\['(ext_trade_[a-z_]+)'\]", r"cfdi_vals.get('\1')", arch
        )

        if arch != view.arch:
            view.write({"arch": arch})

    for wrapper_key, doc_key in WRAPPER_GATE_TARGETS.items():
        view = _get_view(env, wrapper_key)
        if not view:
            continue
        old = (
            "<t t-if=\"o._get_name_invoice_report() == "
            f"'account.report_invoice_document'\" t-call=\"{doc_key}\" t-lang=\"lang\"/>"
        )
        new = f'<t t-call="{doc_key}" t-lang="lang"/>'
        if old in view.arch:
            view.write({"arch": view.arch.replace(old, new)})

    for key in TAX_TOTALS_TEMPLATES_TO_REWRITE:
        view = _get_view(env, key)
        if view:
            view.write({"arch": TAX_TOTALS_TEMPLATE.format(name=key)})

    _fix_internal_note_overlay(env)


def _fix_internal_note_overlay(env):
    """Drop the broken `line.internal_note` column and the stray
    `t-field="line.name"` header attribute added by the Studio overlay on
    top of `account.report_invoice_document_copy_1` (used by "Factura
    Nacional Veco copy(8)")."""
    parent = _get_view(env, "account.report_invoice_document_copy_1")
    if not parent:
        return
    overlay = env["ir.ui.view"].search([
        ("inherit_id", "=", parent.id),
        ("name", "like", "Odoo Studio:"),
    ], limit=1)
    if not overlay:
        return
    arch = overlay.arch

    remove_note_column = (
        '  <xpath expr="/t/t/div/table/thead/tr/th[2]" position="after">\n'
        "    <th>\n"
        "      <span>Nota interna</span>\n"
        "    </th>\n"
        "  </xpath>\n"
        '  <xpath expr="/t/t/div/table/tbody/t[3]/tr/t[1]/td[2]" position="after">\n'
        "    <td>\n"
        '      <span t-field="line.internal_note"/>\n'
        "    </td>\n"
        "  </xpath>\n"
    )
    if remove_note_column in arch:
        arch = arch.replace(remove_note_column, "")

    remove_bad_attribute = (
        '  <xpath expr="/t[1]/t[1]/div[1]/div[7]/div[1]/span[1]" position="attributes">\n'
        '    <attribute name="t-field">line.name</attribute>\n'
        "  </xpath>\n"
    )
    if remove_bad_attribute in arch:
        arch = arch.replace(remove_bad_attribute, "")

    if arch != overlay.arch:
        overlay.write({"arch": arch})
